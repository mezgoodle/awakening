import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../models/player_model.dart';
import '../models/quest_model.dart';
import '../providers/item_provider.dart';
import '../providers/player_provider.dart';
import '../providers/quest_provider.dart';
import '../providers/system_log_provider.dart';
import '../providers/theme_provider.dart';
import '../widgets/quest_card.dart';
import 'system_log_screen.dart';

class QuestsScreen extends StatefulWidget {
  const QuestsScreen({super.key});

  @override
  State<QuestsScreen> createState() => _QuestsScreenState();
}

class _QuestsScreenState extends State<QuestsScreen>
    with SingleTickerProviderStateMixin {
  late TabController _tabController;

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 2, vsync: this);
    _tabController.addListener(() {
      if (mounted) setState(() {});
    });
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  Future<Map<String, dynamic>?> _showQuestGenerationOptionsDialog(
      BuildContext context) async {
    PlayerStat? selectedStat;
    final List<DropdownMenuItem<PlayerStat?>> statItems = [
      const DropdownMenuItem<PlayerStat?>(
        value: null,
        child: Text('Any / General Focus'),
      ),
      ...PlayerStat.values.map((PlayerStat stat) {
        return DropdownMenuItem<PlayerStat?>(
          value: stat,
          child: Text(PlayerModel.getStatName(stat)),
        );
      }),
    ];

    return showDialog<Map<String, dynamic>?>(
      context: context,
      builder: (BuildContext dialogContext) {
        return StatefulBuilder(builder: (context, setStateDialog) {
          return AlertDialog(
            title: const Text('Quest Generation Parameters'),
            content: SingleChildScrollView(
              child: Column(
                mainAxisSize: MainAxisSize.min,
                children: <Widget>[
                  DropdownButtonFormField<PlayerStat?>(
                    decoration: const InputDecoration(
                      labelText: 'Focus Stat (Optional)',
                      border: OutlineInputBorder(),
                    ),
                    value: selectedStat,
                    items: statItems,
                    onChanged: (PlayerStat? newValue) {
                      setStateDialog(() {
                        selectedStat = newValue;
                      });
                    },
                    hint: const Text('Select stat'),
                  ),
                ],
              ),
            ),
            actions: <Widget>[
              TextButton(
                child: const Text('Cancel'),
                onPressed: () => Navigator.of(dialogContext).pop(null),
              ),
              ElevatedButton(
                child: const Text('Generate'),
                onPressed: () {
                  Navigator.of(dialogContext).pop({
                    'targetStat': selectedStat,
                  });
                },
              ),
            ],
          );
        });
      },
    );
  }

  Future<void> _generateNewQuest() async {
    final playerProvider = context.read<PlayerProvider>();
    final questProvider = context.read<QuestProvider>();
    final itemProvider = context.read<ItemProvider>();
    final slog = context.read<SystemLogProvider>();

    if (playerProvider.isLoading) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Hunter data is loading... Please wait.')),
      );
      return;
    }

    if (questProvider.isGeneratingQuest) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('A quest is already being generated by the System...'),
        ),
      );
      return;
    }

    final generationParams = await _showQuestGenerationOptionsDialog(context);
    if (generationParams == null) return;

    final PlayerStat? targetStat =
        generationParams['targetStat'] as PlayerStat?;

    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          duration: Duration(seconds: 8),
          content: Row(
            children: [
              SizedBox(
                width: 20,
                height: 20,
                child: CircularProgressIndicator(strokeWidth: 2),
              ),
              SizedBox(width: 16),
              Text('Consulting the System (Gemini AI)...'),
            ],
          ),
        ),
      );
    }

    final QuestModel? generatedQuest =
        await questProvider.fetchAndAddGeneratedQuest(
      playerProvider: playerProvider,
      targetStat: targetStat,
      slog: slog,
      itemProvider: itemProvider,
    );

    if (mounted) {
      ScaffoldMessenger.of(context).hideCurrentSnackBar();
      if (generatedQuest != null) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Quest "${generatedQuest.title}" received!'),
            backgroundColor: Colors.green[700],
          ),
        );
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final questProvider = context.watch<QuestProvider>();
    final themeProvider = Provider.of<ThemeProvider>(context);

    if (questProvider.isLoading && !questProvider.isGeneratingQuest) {
      return Scaffold(
        appBar: AppBar(title: const Text('Quests')),
        body: const Center(child: CircularProgressIndicator()),
      );
    }

    return Scaffold(
      appBar: AppBar(
        title: const Text('Quests'),
        actions: [
          IconButton(
            icon: Icon(themeProvider.themeMode == ThemeMode.dark
                ? Icons.dark_mode
                : Icons.light_mode),
            tooltip: 'Toggle Theme',
            onPressed: () => themeProvider.toggleTheme(),
          ),
          IconButton(
            icon: const Icon(Icons.notifications_outlined),
            tooltip: 'System Log',
            onPressed: () {
              Navigator.of(context).push(
                MaterialPageRoute(
                  builder: (context) => const SystemLogScreen(),
                ),
              );
            },
          ),
          Consumer<PlayerProvider>(
            builder: (context, playerProviderInstance, child) {
              return IconButton(
                icon: const Icon(Icons.wb_sunny_outlined),
                tooltip: 'Assign Daily Quests',
                onPressed: (questProvider.isGeneratingQuest ||
                        playerProviderInstance.isLoading)
                    ? null
                    : () {
                        final slog = context.read<SystemLogProvider>();
                        questProvider.generateDailyQuestsIfNeeded(
                          playerProviderInstance,
                          slog,
                        );
                      },
              );
            },
          ),
          if (kDebugMode)
            IconButton(
              icon: const Icon(Icons.delete_sweep_outlined),
              tooltip: 'Reset Quests (Debug)',
              onPressed: questProvider.isGeneratingQuest
                  ? null
                  : () async {
                      final bool? confirmReset = await showDialog<bool>(
                        context: context,
                        builder: (BuildContext ctx) {
                          return AlertDialog(
                            title: const Text('Reset All Quests?'),
                            content: const Text(
                              'Delete all active and completed quests for this hunter?',
                            ),
                            actions: <Widget>[
                              TextButton(
                                child: const Text('Cancel'),
                                onPressed: () => Navigator.of(ctx).pop(false),
                              ),
                              TextButton(
                                style: TextButton.styleFrom(
                                  foregroundColor: Colors.red,
                                ),
                                child: const Text('Reset'),
                                onPressed: () => Navigator.of(ctx).pop(true),
                              ),
                            ],
                          );
                        },
                      );
                      if (confirmReset == true) {
                        await questProvider.resetAllQuests();
                        if (mounted) {
                          ScaffoldMessenger.of(context).showSnackBar(
                            const SnackBar(content: Text('All quests reset.')),
                          );
                        }
                      }
                    },
            ),
        ],
        bottom: TabBar(
          controller: _tabController,
          indicatorColor: Colors.lightBlueAccent,
          labelColor: Colors.lightBlueAccent,
          unselectedLabelColor: Colors.grey[400],
          tabs: const [
            Tab(text: 'Active'),
            Tab(text: 'Completed'),
          ],
        ),
      ),
      body: TabBarView(
        controller: _tabController,
        children: [
          _buildQuestList(context, questProvider.activeQuests, true),
          _buildQuestList(context, questProvider.completedQuests, false),
        ],
      ),
      floatingActionButton: _tabController.index == 0
          ? FloatingActionButton.extended(
              onPressed:
                  questProvider.isGeneratingQuest ? null : _generateNewQuest,
              label: questProvider.isGeneratingQuest
                  ? const Text('Generating...')
                  : const Text('New Quest'),
              icon: questProvider.isGeneratingQuest
                  ? Container(
                      width: 18,
                      height: 18,
                      padding: const EdgeInsets.all(2.0),
                      child: const CircularProgressIndicator(
                        strokeWidth: 2,
                        color: Colors.black54,
                      ),
                    )
                  : const Icon(Icons.auto_awesome_outlined),
              backgroundColor: questProvider.isGeneratingQuest
                  ? Colors.grey
                  : Theme.of(context).colorScheme.secondaryContainer,
            )
          : null,
    );
  }

  Widget _buildQuestList(
      BuildContext context, List<QuestModel> quests, bool isActiveList) {
    final playerProvider = context.read<PlayerProvider>();
    if (quests.isEmpty) {
      return Center(
        child: Text(
          isActiveList
              ? 'No active quests.\nTap the sun icon to get daily quests or generate a new one!'
              : 'No completed quests recorded yet.',
          textAlign: TextAlign.center,
          style: Theme.of(context).textTheme.bodyMedium?.copyWith(fontSize: 16),
        ),
      );
    }

    // Sort a copy of the list to prevent mutating state during build
    final sortedQuests = List<QuestModel>.from(quests)
      ..sort((a, b) {
        if (a.type == QuestType.daily && b.type != QuestType.daily) return -1;
        if (a.type != QuestType.daily && b.type == QuestType.daily) return 1;
        final diffCompare = b.difficulty.index.compareTo(a.difficulty.index);
        if (diffCompare != 0) return diffCompare;
        return (b.createdAt ?? DateTime(0))
            .compareTo(a.createdAt ?? DateTime(0));
      });

    return ListView.builder(
      padding: const EdgeInsets.all(12.0),
      itemCount: sortedQuests.length,
      itemBuilder: (context, index) {
        final quest = sortedQuests[index];
        return QuestCard(
          quest: quest,
          onComplete: isActiveList
              ? () {
                  showDialog(
                    context: context,
                    builder: (BuildContext ctx) {
                      return AlertDialog(
                        title: Text('Complete "${quest.title}"?'),
                        content: Text(
                          'Have you verified the completion of this quest in real life?\nReward: ${quest.xpReward} XP',
                        ),
                        actions: <Widget>[
                          TextButton(
                            child: const Text('Cancel'),
                            onPressed: () => Navigator.of(ctx).pop(),
                          ),
                          ElevatedButton(
                            child: const Text('Complete'),
                            onPressed: () {
                              final slog = context.read<SystemLogProvider>();
                              context.read<QuestProvider>().completeQuest(
                                    quest.id,
                                    playerProvider,
                                    slog,
                                  );
                              Navigator.of(ctx).pop();
                            },
                          ),
                        ],
                      );
                    },
                  );
                }
              : null,
        );
      },
    );
  }
}
